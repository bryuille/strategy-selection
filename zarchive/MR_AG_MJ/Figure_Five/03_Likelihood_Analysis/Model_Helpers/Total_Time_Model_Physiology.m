function [alt1, alt2, alt3, alt4, correct] = Total_Time_Model_Physiology( ...
        h1,h2,h3,h4,h5,h6,total_measure,n_trials,scalar, ...
        truth_1,truth_2,truth_3,truth_4)
% Figure 5 physiology-input implementation of the Figure 1 total-time
% policy. Arm lengths and total_measure are supplied in seconds.
assert(numel(total_measure) == n_trials, ...
    'Total-time measurement/trial-count mismatch.');
outcomes = zeros(n_trials, 4);
correct = zeros(1, n_trials);
for trial = 1:n_trials
    scores = [ ...
        D_likelihood_Physiology(scalar,0,total_measure(trial),h1(trial)+h2(trial)), ...
        D_likelihood_Physiology(scalar,0,total_measure(trial),h1(trial)+h3(trial)), ...
        D_likelihood_Physiology(scalar,0,total_measure(trial),h4(trial)+h5(trial)), ...
        D_likelihood_Physiology(scalar,0,total_measure(trial),h4(trial)+h6(trial))];
    tied = find(scores == max(scores));
    selected = tied(randi(numel(tied)));
    outcomes(trial, selected) = 1;
    correct(trial) = isequal(outcomes(trial, :), ...
        [truth_1(trial),truth_2(trial),truth_3(trial),truth_4(trial)]);
end
alt1 = outcomes(:,1)'; alt2 = outcomes(:,2)';
alt3 = outcomes(:,3)'; alt4 = outcomes(:,4)';
end
